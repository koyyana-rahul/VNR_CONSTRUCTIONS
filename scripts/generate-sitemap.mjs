/**
 * ============================================================================
 * GENERATES public/sitemap.xml
 * ============================================================================
 *
 * Built from the ROUTES map and the data files rather than hand-maintained, so
 * a new page cannot be forgotten. Run after adding a route:
 *
 *   node scripts/generate-sitemap.mjs
 *
 * !! The production URL in src/config/company.js is still unconfirmed. The
 * !! sitemap therefore uses whatever company.seo.siteUrl currently says —
 * !! correct it there and re-run before launch.
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { ROUTES } from '../src/config/site.js';
import { projects } from '../src/data/projects.js';
import { services } from '../src/data/services.js';

// Read the production URL straight out of company.js. company.js is an ES
// module, so importing it here would need a loader; a single regex is simpler
// and keeps this script dependency-free.
const companySource = readFileSync(
  new URL('../src/config/company.js', import.meta.url),
  'utf8',
);
const siteUrl =
  /siteUrl:\s*'([^']+)'/.exec(companySource)?.[1] ??
  'https://www.vnrconstructions.com';

/** Pages with a fixed path. */
const STATIC_PATHS = [
  { path: ROUTES.home, priority: '1.0', changefreq: 'weekly' },
  { path: ROUTES.services, priority: '0.9', changefreq: 'monthly' },
  { path: ROUTES.estimate, priority: '0.8', changefreq: 'monthly' },
  { path: ROUTES.packages, priority: '0.8', changefreq: 'monthly' },
  { path: ROUTES.projects, priority: '0.8', changefreq: 'weekly' },
  { path: ROUTES.about, priority: '0.7', changefreq: 'monthly' },
  { path: ROUTES.process, priority: '0.7', changefreq: 'monthly' },
  { path: ROUTES.quality, priority: '0.6', changefreq: 'monthly' },
  { path: ROUTES.contact, priority: '0.7', changefreq: 'monthly' },
  { path: ROUTES.privacy, priority: '0.3', changefreq: 'yearly' },
];

/** Detail pages, generated from the data files. */
const DETAIL_PATHS = [
  ...services.map((s) => ({
    path: `/services/${s.slug}`,
    priority: '0.7',
    changefreq: 'monthly',
  })),
  ...projects.map((p) => ({
    path: `/projects/${p.slug}`,
    priority: '0.6',
    changefreq: 'monthly',
  })),
];

const today = new Date().toISOString().slice(0, 10);

const urls = [...STATIC_PATHS, ...DETAIL_PATHS]
  .map(
    ({ path, priority, changefreq }) => `  <url>
    <loc>${siteUrl}${path}</loc>
    <lastmod>${today}</lastmod>
    <changefreq>${changefreq}</changefreq>
    <priority>${priority}</priority>
  </url>`,
  )
  .join('\n');

const xml = `<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by scripts/generate-sitemap.mjs — do not edit by hand. -->
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${urls}
</urlset>
`;

writeFileSync(new URL('../public/sitemap.xml', import.meta.url), xml, 'utf8');
console.log(`✓ sitemap.xml written with ${STATIC_PATHS.length + DETAIL_PATHS.length} URLs`);
console.log(`  base: ${siteUrl}`);